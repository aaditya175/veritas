import React, { useState, useEffect } from 'react';
import { Table, Download, Search, RefreshCw, FileSpreadsheet } from 'lucide-react';

export default function SyntheticPreviewPage({ dataset }) {
  const [jobs, setJobs] = useState([]);
  const [selectedJobId, setSelectedJobId] = useState('');
  const [jobDetail, setJobDetail] = useState(null);
  const [searchTerm, setSearchTerm] = useState('');
  const [loading, setLoading] = useState(false);

  useEffect(() => {
    if (dataset) {
      loadJobs(dataset.id);
    }
  }, [dataset]);

  const loadJobs = async (dsId) => {
    try {
      const res = await fetch(`/api/generators/jobs/dataset/${dsId}`);
      if (res.ok) {
        const data = await res.json();
        setJobs(data);
        if (data.length > 0) {
          setSelectedJobId(data[0].id);
          fetchJobDetail(data[0].id);
        }
      }
    } catch (e) {
      console.error(e);
    }
  };

  const fetchJobDetail = async (jobId) => {
    setLoading(true);
    try {
      const res = await fetch(`/api/generators/jobs/${jobId}`);
      if (res.ok) {
        const data = await res.json();
        setJobDetail(data);
      }
    } catch (e) {
      console.error(e);
    } finally {
      setLoading(false);
    }
  };

  const handleSelectJob = (id) => {
    setSelectedJobId(id);
    fetchJobDetail(id);
  };

  const rows = jobDetail?.preview_rows || [];
  const filteredRows = rows.filter(r => 
    Object.values(r).some(v => String(v).toLowerCase().includes(searchTerm.toLowerCase()))
  );

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-stone-950 tracking-tight">Synthetic Data Records</h1>
          <p className="text-xs text-stone-500 mt-0.5">
            Scrollable view of sampled synthetic records generated by your fitted models.
          </p>
        </div>

        {selectedJobId && (
          <a
            href={`/api/generators/jobs/${selectedJobId}/download`}
            download
            className="bg-forest-900 hover:bg-forest-950 text-white px-4 py-2 rounded-xl text-xs font-semibold flex items-center gap-2 shadow-xs transition"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download CSV</span>
          </a>
        )}
      </div>

      {/* Generator Job Selector & Search */}
      <div className="bg-white p-4 rounded-2xl border border-stone-200/90 shadow-2xs flex flex-col sm:flex-row items-center justify-between gap-4">
        <div className="flex items-center gap-3 w-full sm:w-auto">
          <span className="text-xs font-semibold text-stone-700 whitespace-nowrap">Model Run:</span>
          <select
            value={selectedJobId}
            onChange={(e) => handleSelectJob(e.target.value)}
            className="bg-stone-50 border border-stone-200 rounded-xl px-3 py-1.5 text-xs text-stone-800 focus:outline-none focus:ring-1 focus:ring-forest-900"
          >
            {jobs.length > 0 ? (
              jobs.map(j => (
                <option key={j.id} value={j.id}>
                  {j.display_name} ({j.num_samples} samples)
                </option>
              ))
            ) : (
              <option value="">No completed runs found yet</option>
            )}
          </select>
        </div>

        <div className="relative w-full sm:w-64">
          <Search className="w-3.5 h-3.5 text-stone-400 absolute left-3 top-2.5" />
          <input
            type="text"
            value={searchTerm}
            onChange={e => setSearchTerm(e.target.value)}
            placeholder="Search in records..."
            className="w-full bg-stone-50 border border-stone-200 rounded-xl pl-8 pr-3 py-1.5 text-xs text-stone-800 focus:outline-none focus:ring-1 focus:ring-forest-900"
          />
        </div>
      </div>

      {/* Scrollable Data Table */}
      <div className="bg-white rounded-2xl border border-stone-200/90 shadow-2xs overflow-hidden">
        <div className="overflow-x-auto max-h-[520px]">
          <table className="w-full text-left text-xs text-stone-700">
            <thead className="bg-stone-50 text-stone-500 font-semibold uppercase tracking-wider text-[10px] sticky top-0 border-b border-stone-200">
              <tr>
                <th className="py-3 px-3.5">#</th>
                {rows[0] && Object.keys(rows[0]).map(col => (
                  <th key={col} className="py-3 px-3.5 whitespace-nowrap">{col}</th>
                ))}
              </tr>
            </thead>
            <tbody className="divide-y divide-stone-100">
              {filteredRows.length > 0 ? (
                filteredRows.map((row, idx) => (
                  <tr key={idx} className="hover:bg-stone-50/70 transition">
                    <td className="py-2.5 px-3.5 text-stone-400 font-mono text-[10px]">{idx + 1}</td>
                    {Object.values(row).map((val, cIdx) => (
                      <td key={cIdx} className="py-2.5 px-3.5 whitespace-nowrap">
                        {typeof val === 'number' ? val.toLocaleString() : String(val)}
                      </td>
                    ))}
                  </tr>
                ))
              ) : (
                <tr>
                  <td colSpan={10} className="py-12 text-center text-stone-400">
                    {jobs.length === 0 ? 'No synthetic data generated yet. Click "Generate Data" in the sidebar.' : 'No rows matching your search filter.'}
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
